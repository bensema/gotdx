// Package gotdx 是通达信行情协议的 Go 客户端库，覆盖主行情、扩展市场、MAC 板块与统一行情、F10 与文件接口。
//
// 本包提供两套互补的调用入口：
//
//   - 高层统一接口：`Stock`*、`Ex`*、`MAC`*、`Goods`* 系列方法，将协议细节封装为简洁的 Go 调用，
//     适合跨市场监控与数据抓取；
//   - 底层协议接口：`Get`*、`ExGet`*、`MACGet`* 系列方法，直接暴露请求构造与响应解码，
//     适合需要控制协议细节的场景。
//
// 客户端通过 `New` 构造，并以 `Option` 配置主站、扩展站、MAC 站地址、地址池、超时与重试行为；
// 内置常用站点地址列表并支持 TCP 测速自动选择最快节点。`Client` 的方法可并发调用，内部串行化
// 同一连接的请求收发。
//
// 市场与周期等共享枚举定义在 `types` 子包，协议请求与响应定义在 `proto` 子包；
// 仓库还附带可直接运行的示例（`examples`）与可视化查询工具（`cmd/webviewer`）。
package gotdx
