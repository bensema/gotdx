// Package proto 实现通达信行情协议的请求构造与响应解码，是 `gotdx` 客户端的协议层。
//
// 每个协议文件以"消息类型 + 请求 + 响应"的形式组织：请求类型实现 `BuildRequest`
// 将参数编码为报文，响应类型实现 `ParseResponse` 从服务端字节流中解码字段；
// 顶层还提供各消息类型编号常量（`KMSG`_*）与报文头、报文长度约定（`MessageHeaderBytes`、
// `MessageMaxBytes`）。
//
// 协议报文默认采用定长字段布局，字段按固定位置排列，日期与时间多以压缩整数编码；
// 具体字段语义以各协议类型的字段注释与仓库协议文档为准。本包不直接管理连接，
// 连接与重试逻辑由根包 `gotdx` 的 `Client` 负责。
